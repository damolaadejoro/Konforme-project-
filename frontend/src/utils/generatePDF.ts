import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'
import { Control, ComplianceScore, ArticleArea } from '../types/controls'
import { format } from 'date-fns'

// Extend jsPDF type to include autoTable
declare module 'jspdf' {
  interface jsPDF {
    lastAutoTable: {
      finalY: number
    }
  }
}

interface PDFData {
  companyName: string
  complianceScore: ComplianceScore
  controls: Control[]
  articleAreas: ArticleArea[]
  criticalGaps: Control[]
}

// Brand colors
const COLORS = {
  navy: '#0B1F3A',
  cyan: '#00C2D4',
  white: '#FFFFFF',
  lightGray: '#F3F4F6',
  darkGray: '#6B7280',
  red: '#EF4444',
  yellow: '#F59E0B',
  emerald: '#10B981',
  orange: '#F97316'
}

// Status colors
const getStatusColor = (status: string): string => {
  switch (status) {
    case 'Implemented': return COLORS.emerald
    case 'Partial': return COLORS.yellow
    case 'Planned': return COLORS.orange
    case 'Not Started': return COLORS.red
    default: return COLORS.darkGray
  }
}

// Get score color
const getScoreColor = (score: number): string => {
  if (score >= 75) return COLORS.emerald
  if (score >= 50) return COLORS.yellow
  return COLORS.red
}

// Get executive summary text based on score
const getExecutiveSummary = (score: number): string => {
  if (score >= 91) {
    return 'This assessment demonstrates strong NIS2 compliance posture across all Article 21 requirement areas.'
  } else if (score >= 71) {
    return 'This assessment shows good compliance progress. Remaining gaps should be addressed to achieve full NIS2 readiness ahead of enforcement.'
  } else if (score >= 41) {
    return 'This assessment identifies moderate compliance gaps. Priority should be given to critical and high severity controls to achieve full NIS2 readiness.'
  } else {
    return 'This assessment identifies significant gaps across NIS2 Article 21 requirements. Immediate action is required to address critical controls before enforcement proceedings.'
  }
}

// Add header to page
const addHeader = (doc: jsPDF, pageNumber: number) => {
  if (pageNumber === 1) return // No header on cover page

  doc.setFillColor(COLORS.navy)
  doc.rect(0, 0, doc.internal.pageSize.width, 20, 'F')

  // Logo/brand
  doc.setFontSize(12)
  doc.setTextColor(COLORS.cyan)
  doc.setFont('helvetica', 'bold')
  doc.text('⚡ Konforme', 14, 13)

  // Page number
  doc.setFontSize(9)
  doc.setTextColor(COLORS.white)
  doc.text(`Page ${pageNumber}`, doc.internal.pageSize.width - 14, 13, { align: 'right' })
}

// Add footer to page
const addFooter = (doc: jsPDF, isLastPage = false) => {
  const pageHeight = doc.internal.pageSize.height

  doc.setFontSize(8)
  doc.setTextColor(COLORS.darkGray)

  if (isLastPage) {
    doc.text('This report was generated by Konforme. For more information visit konforme.io', 14, pageHeight - 10)
  } else {
    doc.text(`Generated on ${format(new Date(), 'MMMM d, yyyy')}`, 14, pageHeight - 10)
  }
}

export async function generateComplianceReport(data: PDFData): Promise<void> {
  const doc = new jsPDF()
  const pageWidth = doc.internal.pageSize.width
  const pageHeight = doc.internal.pageSize.height
  let pageNumber = 1

  // ===================
  // PAGE 1: Cover Page
  // ===================

  // Background
  doc.setFillColor(COLORS.navy)
  doc.rect(0, 0, pageWidth, pageHeight, 'F')

  // Shield/Logo - Simple representation
  doc.setFillColor(COLORS.cyan)
  const shieldX = pageWidth / 2 - 15
  doc.circle(pageWidth / 2, 50, 20, 'F')
  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text('⚡', pageWidth / 2, 55, { align: 'center' })

  // Title
  doc.setTextColor(COLORS.white)
  doc.setFontSize(32)
  doc.setFont('helvetica', 'bold')
  doc.text('NIS2 Compliance Report', pageWidth / 2, 95, { align: 'center' })

  // Subtitle
  doc.setFontSize(16)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(COLORS.cyan)
  doc.text('Article 21 Readiness Assessment', pageWidth / 2, 110, { align: 'center' })

  // Company name
  doc.setFontSize(20)
  doc.setTextColor(COLORS.white)
  doc.setFont('helvetica', 'bold')
  doc.text(data.companyName, pageWidth / 2, 140, { align: 'center' })

  // Report date
  doc.setFontSize(12)
  doc.setTextColor(COLORS.darkGray)
  doc.setFont('helvetica', 'normal')
  doc.text(`Report Date: ${format(new Date(), 'MMMM d, yyyy')}`, pageWidth / 2, 160, { align: 'center' })

  // Generated by
  doc.setFontSize(10)
  doc.text('Generated by:', pageWidth / 2, 200, { align: 'center' })
  doc.setTextColor(COLORS.cyan)
  doc.setFont('helvetica', 'bold')
  doc.text('Konforme — NIS2 Compliance Platform', pageWidth / 2, 208, { align: 'center' })
  doc.setTextColor(COLORS.white)
  doc.setFont('helvetica', 'normal')
  doc.text('konforme.io', pageWidth / 2, 216, { align: 'center' })

  // =============================
  // PAGE 2: Executive Summary
  // =============================

  doc.addPage()
  pageNumber++
  addHeader(doc, pageNumber)

  let yPos = 35

  // Title
  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text('Executive Summary', 14, yPos)
  yPos += 15

  // Overall Score - Large
  const scoreColor = getScoreColor(data.complianceScore.overall)
  doc.setFillColor(scoreColor)
  doc.roundedRect(14, yPos, 80, 40, 3, 3, 'F')
  doc.setTextColor(COLORS.white)
  doc.setFontSize(36)
  doc.setFont('helvetica', 'bold')
  doc.text(`${data.complianceScore.overall}%`, 54, yPos + 20, { align: 'center' })
  doc.setFontSize(12)
  doc.setFont('helvetica', 'normal')
  doc.text('Overall NIS2 Readiness', 54, yPos + 32, { align: 'center' })
  yPos += 50

  // Score Breakdown Table
  doc.setFontSize(14)
  doc.setTextColor(COLORS.navy)
  doc.setFont('helvetica', 'bold')
  doc.text('Score Breakdown', 14, yPos)
  yPos += 5

  autoTable(doc, {
    startY: yPos,
    head: [['Category', 'Score', 'Status']],
    body: [
      ['Technical Controls', `${data.complianceScore.technical}%`, data.complianceScore.technical >= 75 ? 'Good' : data.complianceScore.technical >= 50 ? 'At Risk' : 'Critical'],
      ['Organizational Controls', `${data.complianceScore.organizational}%`, data.complianceScore.organizational >= 75 ? 'Good' : data.complianceScore.organizational >= 50 ? 'At Risk' : 'Critical'],
      ['People & Culture', `${data.complianceScore.people}%`, data.complianceScore.people >= 75 ? 'Good' : data.complianceScore.people >= 50 ? 'At Risk' : 'Critical'],
    ],
    theme: 'grid',
    headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold' },
    styles: { fontSize: 10, cellPadding: 5 },
    columnStyles: {
      0: { cellWidth: 80 },
      1: { cellWidth: 40, halign: 'center' },
      2: { cellWidth: 60, halign: 'center' }
    }
  })

  yPos = doc.lastAutoTable.finalY + 10

  // Control Status Summary
  const totalControls = data.controls.length
  const implemented = data.controls.filter(c => c.status === 'Implemented').length
  const partial = data.controls.filter(c => c.status === 'Partial').length
  const planned = data.controls.filter(c => c.status === 'Planned').length
  const notStarted = data.controls.filter(c => c.status === 'Not Started').length

  doc.setFontSize(14)
  doc.setTextColor(COLORS.navy)
  doc.setFont('helvetica', 'bold')
  doc.text('Control Status Summary', 14, yPos)
  yPos += 5

  autoTable(doc, {
    startY: yPos,
    head: [['Status', 'Count', 'Percentage']],
    body: [
      ['Implemented', implemented.toString(), `${Math.round((implemented / totalControls) * 100)}%`],
      ['Partial', partial.toString(), `${Math.round((partial / totalControls) * 100)}%`],
      ['Planned', planned.toString(), `${Math.round((planned / totalControls) * 100)}%`],
      ['Not Started', notStarted.toString(), `${Math.round((notStarted / totalControls) * 100)}%`],
      ['TOTAL', totalControls.toString(), '100%']
    ],
    theme: 'grid',
    headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold' },
    styles: { fontSize: 10, cellPadding: 5 },
    columnStyles: {
      0: { cellWidth: 80 },
      1: { cellWidth: 40, halign: 'center' },
      2: { cellWidth: 60, halign: 'center' }
    },
    didParseCell: (data) => {
      if (data.row.index === 4 && data.section === 'body') {
        data.cell.styles.fontStyle = 'bold'
        data.cell.styles.fillColor = COLORS.lightGray
      }
    }
  })

  yPos = doc.lastAutoTable.finalY + 10

  // Critical Gaps
  doc.setFontSize(11)
  doc.setTextColor(COLORS.navy)
  doc.setFont('helvetica', 'bold')
  doc.text(`Critical Gaps Identified: ${data.criticalGaps.length}`, 14, yPos)
  yPos += 8

  // Executive Summary Text
  doc.setFontSize(10)
  doc.setTextColor(COLORS.darkGray)
  doc.setFont('helvetica', 'normal')
  const summaryText = getExecutiveSummary(data.complianceScore.overall)
  const splitSummary = doc.splitTextToSize(summaryText, pageWidth - 28)
  doc.text(splitSummary, 14, yPos)

  addFooter(doc)

  // =================================
  // PAGE 3: Article 21 Coverage Map
  // =================================

  doc.addPage()
  pageNumber++
  addHeader(doc, pageNumber)

  yPos = 35

  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text('Article 21 Coverage Map', 14, yPos)
  yPos += 5

  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(COLORS.darkGray)
  doc.text('Compliance status across all NIS2 Article 21 requirement areas', 14, yPos + 5)
  yPos += 15

  autoTable(doc, {
    startY: yPos,
    head: [['Article', 'Requirement Area', 'Status', 'Progress', 'Maturity']],
    body: data.articleAreas.map(area => [
      area.article,
      area.name,
      area.status,
      `${area.implementedCount}/${area.controlCount}`,
      `${Math.round((area.implementedCount / area.controlCount) * 100)}%`
    ]),
    theme: 'grid',
    headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold', fontSize: 9 },
    styles: { fontSize: 9, cellPadding: 4 },
    columnStyles: {
      0: { cellWidth: 25, fontStyle: 'bold' },
      1: { cellWidth: 70 },
      2: { cellWidth: 30, halign: 'center' },
      3: { cellWidth: 25, halign: 'center' },
      4: { cellWidth: 25, halign: 'center' }
    },
    didParseCell: (data) => {
      if (data.column.index === 2 && data.section === 'body') {
        const status = data.cell.text[0]
        data.cell.styles.textColor = getStatusColor(status)
        data.cell.styles.fontStyle = 'bold'
      }
    }
  })

  addFooter(doc)

  // ===================================
  // PAGE 4+: Controls Detail (by area)
  // ===================================

  // Group controls by article area
  const controlsByArea: Record<string, Control[]> = {}
  data.controls.forEach(control => {
    if (!controlsByArea[control.articleArea]) {
      controlsByArea[control.articleArea] = []
    }
    controlsByArea[control.articleArea].push(control)
  })

  // Sort areas
  const sortedAreas = Object.keys(controlsByArea).sort()

  for (const areaName of sortedAreas) {
    const areaControls = controlsByArea[areaName]

    doc.addPage()
    pageNumber++
    addHeader(doc, pageNumber)

    yPos = 35

    // Area title
    doc.setTextColor(COLORS.navy)
    doc.setFontSize(18)
    doc.setFont('helvetica', 'bold')
    doc.text(areaName, 14, yPos)
    yPos += 10

    // Controls table
    const controlRows = areaControls.map(control => {
      const evidenceCount = control.evidence.length
      const evidenceText = evidenceCount > 0
        ? `${evidenceCount} file${evidenceCount > 1 ? 's' : ''}`
        : 'None'

      return [
        control.title,
        control.article,
        control.status,
        control.owner || 'Unassigned',
        control.dueDate ? format(new Date(control.dueDate), 'MMM d, yyyy') : 'No date',
        evidenceText
      ]
    })

    autoTable(doc, {
      startY: yPos,
      head: [['Control', 'Article', 'Status', 'Owner', 'Due Date', 'Evidence']],
      body: controlRows,
      theme: 'grid',
      headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold', fontSize: 8 },
      styles: { fontSize: 8, cellPadding: 3 },
      columnStyles: {
        0: { cellWidth: 60 },
        1: { cellWidth: 25, fontSize: 7 },
        2: { cellWidth: 25, halign: 'center' },
        3: { cellWidth: 30 },
        4: { cellWidth: 25, halign: 'center', fontSize: 7 },
        5: { cellWidth: 20, halign: 'center', fontSize: 7 }
      },
      didParseCell: (data) => {
        if (data.column.index === 2 && data.section === 'body') {
          const status = data.cell.text[0]
          data.cell.styles.textColor = getStatusColor(status)
          data.cell.styles.fontStyle = 'bold'
        }
        // Highlight gaps
        if (data.section === 'body') {
          const status = controlRows[data.row.index][2]
          if (status === 'Not Started' || status === 'Planned') {
            data.cell.styles.fillColor = '#FEF3C7' // Light yellow
          }
        }
      }
    })

    addFooter(doc)
  }

  // ============================
  // FINAL PAGE: Recommendations
  // ============================

  doc.addPage()
  pageNumber++
  addHeader(doc, pageNumber)

  yPos = 35

  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text('Recommendations', 14, yPos)
  yPos += 15

  // Get top gaps (Not Started controls)
  const gaps = data.controls
    .filter(c => c.status === 'Not Started')
    .sort((a, b) => {
      const severityOrder = { critical: 0, high: 1, medium: 2 }
      return severityOrder[a.severity] - severityOrder[b.severity]
    })
    .slice(0, 10)

  if (gaps.length === 0) {
    doc.setFontSize(12)
    doc.setTextColor(COLORS.emerald)
    doc.text('Excellent! No critical gaps identified.', 14, yPos)
    doc.setFontSize(10)
    doc.setTextColor(COLORS.darkGray)
    doc.text('Continue to maintain and monitor your compliance posture.', 14, yPos + 8)
  } else {
    doc.setFontSize(11)
    doc.setTextColor(COLORS.darkGray)
    doc.setFont('helvetica', 'normal')
    doc.text('The following controls require immediate attention:', 14, yPos)
    yPos += 10

    gaps.forEach((control, index) => {
      if (yPos > pageHeight - 40) {
        doc.addPage()
        pageNumber++
        addHeader(doc, pageNumber)
        yPos = 35
      }

      // Gap number
      doc.setFillColor(COLORS.cyan)
      doc.circle(18, yPos - 1, 3, 'F')
      doc.setTextColor(COLORS.white)
      doc.setFontSize(9)
      doc.setFont('helvetica', 'bold')
      doc.text(`${index + 1}`, 18, yPos + 1, { align: 'center' })

      // Control title
      doc.setTextColor(COLORS.navy)
      doc.setFontSize(11)
      doc.setFont('helvetica', 'bold')
      doc.text(control.title, 24, yPos)

      // Article and severity
      doc.setFontSize(9)
      doc.setFont('helvetica', 'normal')
      doc.setTextColor(COLORS.darkGray)
      doc.text(`${control.article} • ${control.severity.toUpperCase()} severity`, 24, yPos + 5)

      // Recommended action
      doc.setFontSize(9)
      doc.setTextColor(COLORS.darkGray)
      const actionText = `Action: Assign owner, set due date, and document implementation plan.`
      const splitAction = doc.splitTextToSize(actionText, pageWidth - 38)
      doc.text(splitAction, 24, yPos + 10)

      yPos += 20
    })
  }

  // Final footer
  yPos = pageHeight - 30
  doc.setDrawColor(COLORS.cyan)
  doc.setLineWidth(0.5)
  doc.line(14, yPos, pageWidth - 14, yPos)
  yPos += 10

  doc.setFontSize(10)
  doc.setTextColor(COLORS.darkGray)
  doc.setFont('helvetica', 'normal')
  doc.text('This report was generated by Konforme.', 14, yPos)
  doc.setTextColor(COLORS.cyan)
  doc.setFont('helvetica', 'bold')
  doc.text('For more information visit konforme.io', 14, yPos + 6)

  // Save the PDF
  const filename = `Konforme-NIS2-Report-${format(new Date(), 'yyyy-MM-dd')}.pdf`
  doc.save(filename)
}

def get_email_text(lang: str, key: str, **kwargs) -> str:
    """Get translated email text with variable substitution and English fallback."""
    strings = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    text = strings.get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        text = text.format(**kwargs)
    return text

@router.post("/remediation/{account_id}/{task_id}/close", response_model=RemediationTaskResponse)
def close_task(
    account_id: str,
    task_id: str,
    req: CloseTaskRequest,
    account: Account = Depends(get_current_account),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    enforce_account_access(account, account_id)
    task = _get_task_or_404(db, account_id, task_id)

    if task.status not in ("open", "in_progress"):
        raise HTTPException(status_code=409, detail=f"Cannot close task in status '{task.status}'")
    if not req.closure_evidence_id and not req.closure_note:
        raise HTTPException(status_code=422, detail="Either closure_evidence_id or closure_note is required")

    remediation_service.close_task(
        db, task,
        closure_evidence_id=req.closure_evidence_id,
        closure_note=req.closure_note,
        actor_user_id=user.id,
        actor_email=user.email,
    )
    db.commit()
    return _task_to_response(task)



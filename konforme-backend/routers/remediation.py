def _task_to_response(t: RemediationTask) -> RemediationTaskResponse:
    return RemediationTaskResponse(
        id=t.id,
        questionId=t.question_id,
        title=t.title,
        description=t.description,
        status=t.status,
        priority=t.priority,
        assignedTo=t.assigned_to,
        dueDate=t.due_date.isoformat() if t.due_date else None,
        createdAt=t.created_at.isoformat(),
        updatedAt=t.updated_at.isoformat(),
        completedAt=t.completed_at.isoformat() if t.completed_at else None,
        planId=t.plan_id,
        relatedControlId=t.related_control_id,
        severity=t.severity or "medium",
        autoGenerated=t.auto_generated or False,
        closureNote=t.closure_note,
        closureEvidenceId=t.closure_evidence_id,
        dismissedReason=t.dismissed_reason,
        dismissedAt=t.dismissed_at.isoformat() if t.dismissed_at else None,
        originalDueDate=t.original_due_date.isoformat() if t.original_due_date else None,
        rescheduleCount=t.reschedule_count or 0,
        chronicSlip=remediation_service.is_chronic_slip(t),
    )


def _plan_to_response(p: RemediationPlan) -> RemediationPlanResponse:
    tasks = p.tasks or []
    return RemediationPlanResponse(
        id=p.id,
        title=p.title,
        description=p.description,
        treatmentType=p.treatment_type,
        status=p.status,
        targetDate=p.target_date.isoformat() if p.target_date else None,
        createdByUserId=p.created_by_user_id,
        approvedByUserId=p.approved_by_user_id,
        approvedAt=p.approved_at.isoformat() if p.approved_at else None,
        rejectedByUserId=p.rejected_by_user_id,
        rejectedAt=p.rejected_at.isoformat() if p.rejected_at else None,
        rejectionReason=p.rejection_reason,
        createdAt=p.created_at.isoformat(),
        updatedAt=p.updated_at.isoformat(),
        milestones=[
            MilestoneResponse(
                id=m.id,
                title=m.title,
                description=m.description,
                targetDate=m.target_date.isoformat() if m.target_date else None,
                completedAt=m.completed_at.isoformat() if m.completed_at else None,
                displayOrder=m.display_order,
            ) for m in sorted(p.milestones or [], key=lambda x: x.display_order)
        ],
        links=[
            PlanLinkResponse(id=lk.id, entityType=lk.entity_type, entityId=lk.entity_id)
            for lk in (p.links or [])
        ],
        taskCount=len(tasks),
        completedTaskCount=sum(1 for t in tasks if t.status == "completed"),
    )


def _plan_to_summary(p: RemediationPlan) -> RemediationPlanSummary:
    tasks = p.tasks or []
    milestones = p.milestones or []
    return RemediationPlanSummary(
        id=p.id,
        title=p.title,
        treatmentType=p.treatment_type,
        status=p.status,
        targetDate=p.target_date.isoformat() if p.target_date else None,
        createdAt=p.created_at.isoformat(),
        taskCount=len(tasks),
        completedTaskCount=sum(1 for t in tasks if t.status == "completed"),
        milestoneCount=len(milestones),
        completedMilestoneCount=sum(1 for m in milestones if m.completed_at),
    )


def _get_task_or_404(db: Session, account_id: str, task_id: str) -> RemediationTask:
    task = db.get_by_key(RemediationTask, account_id, id=task_id)
    if not task:
        raise HTTPException(status_code=404, detail="Remediation task not found")
    return task


def _get_plan_or_404(db: Session, account_id: str, plan_id: str) -> RemediationPlan:
    plan = db.get_by_key(RemediationPlan, account_id, id=plan_id)
    if not plan:
        raise HTTPException(status_code=404, detail="Remediation plan not found")
    return plan



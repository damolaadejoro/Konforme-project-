@router.patch("/remediation/{account_id}/plans/{plan_id}", response_model=RemediationPlanResponse)
def update_plan(
    account_id: str,
    plan_id: str,
    req: UpdateRemediationPlanRequest,
    account: Account = Depends(get_current_account),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    enforce_account_access(account, account_id)
    plan = _get_plan_or_404(db, account_id, plan_id)

    # Material changes require change_reason
    material_fields = {"treatment_type", "target_date"}
    updates = req.model_dump(exclude_none=True)
    has_material = any(k in material_fields for k in updates)
    if has_material and not req.change_reason:
        raise HTTPException(status_code=422, detail="change_reason required for material changes (treatment_type, target_date)")

    if req.target_date:
        updates["target_date"] = date.fromisoformat(req.target_date)

    updates.pop("change_reason", None)
    remediation_service.update_plan(
        db, plan, updates,
        change_reason=req.change_reason,
        actor_user_id=user.id,
        actor_email=user.email,
    )
    db.commit()
    return _plan_to_response(plan)


@router.post("/remediation/{account_id}/plans/{plan_id}/approve", response_model=RemediationPlanResponse)
def approve_or_reject_plan(
    account_id: str,
    plan_id: str,
    req: PlanApprovalRequest,
    account: Account = Depends(get_current_account),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    enforce_account_access(account, account_id)
    plan = _get_plan_or_404(db, account_id, plan_id)

    if plan.status not in ("draft", "pending_approval"):
        raise HTTPException(status_code=409, detail=f"Plan cannot be {req.action}d in status '{plan.status}'")

    if req.action == "approve":
        remediation_service.approve_plan(db, plan, user.id, user.email)
    else:
        if not req.rejection_reason:
            raise HTTPException(status_code=422, detail="rejection_reason required")
        remediation_service.reject_plan(db, plan, req.rejection_reason, user.id, user.email)

    db.commit()
    return _plan_to_response(plan)



@router.post("/remediation/{account_id}/plans", response_model=RemediationPlanResponse)
def create_plan(
    account_id: str,
    req: CreateRemediationPlanRequest,
    account: Account = Depends(get_current_account),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    enforce_account_access(account, account_id)

    target = date.fromisoformat(req.target_date) if req.target_date else None
